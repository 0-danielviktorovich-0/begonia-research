#!/usr/bin/env python3
"""gen_archive_index.py — regenerate archive/index.html.

Pairs every offline copy in archive/ with its original URL. Mapping is read from a simple
manifest file (default: archive/index-manifest.tsv) with tab-separated columns:
    file<TAB>original_url<TAB>type<TAB>cited_in
Rows for files present on disk but missing from the manifest are appended as UNMAPPED (so
nothing disappears from the index silently).

Usage: python3 gen_archive_index.py [archive_dir]
"""
import html
import os
import sys

A = sys.argv[1] if len(sys.argv) > 1 else "archive"
MANIFEST = os.path.join(A, "index-manifest.tsv")
OUT = os.path.join(A, "index.html")

entries = []
if os.path.exists(MANIFEST):
    for line in open(MANIFEST, encoding="utf-8"):
        parts = line.rstrip("\n").split("\t")
        if len(parts) >= 2 and parts[0] and not parts[0].startswith("#"):
            parts += [""] * (4 - len(parts))
            entries.append(parts[:4])

on_disk = set()
for root, _dirs, files in os.walk(A):
    for f in files:
        if f.endswith((".html", ".md", ".txt", ".json")) and f != "index.html" and not (root == A and f == "README.md"):
            rel = os.path.relpath(os.path.join(root, f), A)
            on_disk.add(rel)

mapped = {e[0] for e in entries}
for f in sorted(on_disk - mapped):
    entries.append([f, "(unmapped — add to index-manifest.tsv)", "auto-discovered", ""])

rows = []
for f, url, typ, used in sorted(entries):
    p = os.path.join(A, f)
    if not os.path.exists(p):
        rows.append(f"<tr><td>{html.escape(f)}</td><td colspan='4'><b>MISSING</b></td></tr>")
        continue
    size = os.path.getsize(p) // 1024
    rows.append(
        f"<tr><td><a href='{html.escape(f)}' style='font-family:monospace'>{html.escape(f)}</a></td>"
        f"<td><a href='{html.escape(url)}'>{html.escape(url[:80])}{'…' if len(url) > 80 else ''}</a></td>"
        f"<td>{html.escape(typ)}</td><td>{size} KB</td><td>{html.escape(used)}</td></tr>"
    )

page = f"""<!doctype html><html lang=en><head><meta charset=utf-8>
<title>offline archive index</title>
<style>
body{{font-family:-apple-system,Segoe UI,Roboto,sans-serif;margin:2rem;max-width:1200px}}
table{{border-collapse:collapse;width:100%}}td,th{{border:1px solid #ccc;padding:6px 8px;font-size:13px;text-align:left;vertical-align:top}}
th{{background:#f3f3f3}}tr:nth-child(even){{background:#fafafa}}
.note{{background:#fff8e1;border:1px solid #e0c96b;padding:10px 14px;border-radius:6px;margin:14px 0}}
</style></head><body>
<h1>Offline archive index</h1>
<p>Each row pairs the <b>original source</b> with its <b>offline copy</b> (click the filename).
Binary firmware/kernel images are intentionally not archived; small text artifacts live under <code>files/</code>.</p>
<table><tr><th>Offline copy</th><th>Original</th><th>Type</th><th>Size</th><th>Cited in</th></tr>
{''.join(rows)}
</table>
<p><i>Generated by tools/gen_archive_index.py — observation-anchored: the manifest records what was seen, not a guarantee.</i></p>
</body></html>"""
open(OUT, "w").write(page)
print(f"{OUT}: {len(rows)} rows, {os.path.getsize(OUT)} bytes ({len(mapped)} mapped, {len(on_disk - mapped)} unmapped)")
